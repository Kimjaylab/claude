def seconds_to_hhmmss(t: float) -> str:
    total_s = int(abs(t))
    h = total_s // 3600
    m = (total_s % 3600) // 60
    s = total_s % 60
    sign = "-" if t < 0 else ""
    return f"{sign}{h:02d}:{m:02d}:{s:02d}"


def seconds_to_ms(t: float) -> str:
    """초 → ms 정수 문자열."""
    return str(round(t * 1000))


