SLIP_END     = 0xC0
SLIP_ESC     = 0xDB
SLIP_ESC_END = 0xDC
SLIP_ESC_ESC = 0xDD


def slip_decode(data: bytes) -> list:
    """SLIP 바이너리에서 패킷 목록 추출."""
    packets = []
    current = bytearray()
    i = 0
    while i < len(data):
        b = data[i]
        if b == SLIP_END:
            if current:
                packets.append(bytes(current))
                current = bytearray()
        elif b == SLIP_ESC:
            i += 1
            if i < len(data):
                nb = data[i]
                if nb == SLIP_ESC_END:
                    current.append(SLIP_END)
                elif nb == SLIP_ESC_ESC:
                    current.append(SLIP_ESC)
                else:
                    current.append(nb)
        else:
            current.append(b)
        i += 1
    if current:
        packets.append(bytes(current))
    return packets


